// Compiles horus_capture's compositor shader (gta/capture/src/composite.hlsl) to DXBC (vs_5_0 /
// ps_5_0) with D3DCompile from d3dcompiler_47.dll and writes the bytecode as a C++ header, so the
// plugin needs no shader compiler in the game. Built by gta/build.sh; run under wine (its builtin
// d3dcompiler_47 compiles HLSL with vkd3d-shader):
//
//   WINEDEBUG=-all wine gta/build/horus_shader_gen.exe gta/capture/src/composite.hlsl gta/capture/src/composite_shaders.hpp
//
// The header records an FNV-1a hash of the source; horus_capture_tests.exe checks it against the
// .hlsl, so a shader edit without regenerating fails the tests.

#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <d3dcompiler.h>

#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>

#include "../src/shader_hash.hpp"

namespace {

using D3DCompileFn = HRESULT(WINAPI*)(const void*, SIZE_T, const char*, const D3D_SHADER_MACRO*, ID3DInclude*,
                                      const char*, const char*, UINT, UINT, ID3DBlob**, ID3DBlob**);

bool compile(D3DCompileFn fn, const std::string& source, const char* entry, const char* target, std::string& bytes) {
    ID3DBlob* blob = nullptr;
    ID3DBlob* messages = nullptr;
    const HRESULT hr = fn(source.data(), source.size(), "composite.hlsl", nullptr, nullptr, entry, target,
                          D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, &blob, &messages);
    if (messages) {
        std::fprintf(stderr, "%s: %s\n", entry, static_cast<const char*>(messages->GetBufferPointer()));
        messages->Release();
    }
    if (FAILED(hr) || !blob) {
        std::fprintf(stderr, "compiling %s (%s) failed: hr 0x%08lx\n", entry, target, static_cast<unsigned long>(hr));
        return false;
    }
    bytes.assign(static_cast<const char*>(blob->GetBufferPointer()), blob->GetBufferSize());
    blob->Release();
    return true;
}

void write_array(std::ostringstream& out, const char* name, const std::string& bytes) {
    out << "alignas(4) constexpr unsigned char " << name << "[] = {";
    for (size_t i = 0; i < bytes.size(); ++i) {
        char hex[8];
        std::snprintf(hex, sizeof(hex), "0x%02x,", static_cast<unsigned char>(bytes[i]));
        out << (i % 16 == 0 ? "\n    " : " ") << hex;
    }
    out << "\n};\n";
}

// "wine 11.20" when running under wine, else "Windows".
std::string runtime_name() {
    using GetVersionFn = const char*(CDECL*)();
    HMODULE ntdll = GetModuleHandleW(L"ntdll.dll");
    auto fn = ntdll ? reinterpret_cast<GetVersionFn>(reinterpret_cast<void*>(GetProcAddress(ntdll, "wine_get_version")))
                    : nullptr;
    return fn ? std::string("wine ") + fn() : std::string("Windows");
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 3) {
        std::fprintf(stderr, "usage: %s composite.hlsl composite_shaders.hpp\n", argv[0]);
        return 2;
    }
    std::ifstream in(argv[1], std::ios::binary);
    if (!in) {
        std::fprintf(stderr, "cannot read %s\n", argv[1]);
        return 1;
    }
    const std::string source((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    HMODULE compiler = LoadLibraryW(L"d3dcompiler_47.dll");
    auto fn = compiler ? reinterpret_cast<D3DCompileFn>(reinterpret_cast<void*>(GetProcAddress(compiler, "D3DCompile")))
                       : nullptr;
    if (!fn) {
        std::fprintf(stderr, "d3dcompiler_47.dll (D3DCompile) not available\n");
        return 1;
    }
    std::string vs;
    std::string ps;
    if (!compile(fn, source, "vs_main", "vs_5_0", vs) || !compile(fn, source, "ps_main", "ps_5_0", ps)) return 1;

    char hash[16];
    std::snprintf(hash, sizeof(hash), "0x%08xu", static_cast<unsigned>(horus::capture::fnv1a(source)));
    std::ostringstream out;
    out << "// Generated by gta/capture/tools/shader_gen.cpp from composite.hlsl; do not edit. Regenerate with\n"
           "//   WINEDEBUG=-all wine gta/build/horus_shader_gen.exe gta/capture/src/composite.hlsl "
           "gta/capture/src/composite_shaders.hpp\n"
           "// Compiler: d3dcompiler_47.dll D3DCompile ("
        << runtime_name()
        << "), vs_5_0 / ps_5_0, optimization level 3.\n"
           "#pragma once\n\n"
           "#include <cstdint>\n\n"
           "namespace horus::capture {\n\n"
           "constexpr uint32_t kCompositeHlslHash = "
        << hash << ";  // fnv1a(composite.hlsl), shader_hash.hpp\n\n";
    write_array(out, "kCompositeVs", vs);
    out << "\n";
    write_array(out, "kCompositePs", ps);
    out << "\n}  // namespace horus::capture\n";

    std::ofstream file(argv[2], std::ios::binary);
    file << out.str();
    if (!file.flush()) {
        std::fprintf(stderr, "cannot write %s\n", argv[2]);
        return 1;
    }
    std::printf("wrote %s: vs %zu bytes, ps %zu bytes, source hash %s\n", argv[2], vs.size(), ps.size(), hash);
    return 0;
}
